// Helper functions to get summary data
export const getSummaryData = () => {
  const totalProperties = pgs.length
  const totalTenants = tenants.filter((tenant) => tenant.status === "active").length
  const totalAvailableBeds = pgs.reduce((sum, pg) => sum + pg.available_beds, 0)
  const monthlyRevenue = rents.reduce((sum, rent) => sum + (rent.status === "paid" ? rent.amount_paid : 0), 0)
  const recentIssues = issues.filter((issue) => issue.status !== "resolved").length

  return {
    totalProperties,
    totalTenants,
    totalAvailableBeds,
    monthlyRevenue,
    recentIssues,
  }
}

